const setPath = (object, dotted, value) => {
  const keys = dotted.split(".");
  const last = keys.pop();
  const parent = keys.reduce((acc, k) => acc[k], object);
  parent[last] = value;
};

export function applyPlan(snapshot, plan) {
  const wf = structuredClone(snapshot);
  const named = (name) => {
    const node = wf.nodes.find((n) => n.name === name);
    if (!node) throw new Error(`plan refers to a node the workflow lacks: ${name}`);
    return node;
  };
  for (const op of plan.operations) {
    if (op.type === "removeNode") {
      named(op.nodeName);
      wf.nodes = wf.nodes.filter((n) => n.name !== op.nodeName);
      delete wf.connections[op.nodeName];
      for (const outputs of Object.values(wf.connections)) {
        outputs.main = (outputs.main ?? []).map((list) => (list ?? []).filter((c) => c.node !== op.nodeName));
      }
    } else if (op.type === "addNode") {
      if (wf.nodes.some((n) => n.name === op.node.name)) throw new Error(`node already exists: ${op.node.name}`);
      wf.nodes.push(structuredClone(op.node));
    } else if (op.type === "updateNode") {
      const node = named(op.nodeName);
      for (const [dotted, value] of Object.entries(op.updates)) setPath(node, dotted, value);
    } else if (op.type === "addConnection") {
      named(op.source);
      named(op.target);
      const index = op.branch === "false" ? 1 : 0;
      const outputs = (wf.connections[op.source] = wf.connections[op.source] ?? { main: [] });
      while (outputs.main.length <= index) outputs.main.push([]);
      outputs.main[index].push({ node: op.target, type: "main", index: 0 });
    } else {
      throw new Error(`unknown operation: ${op.type}`);
    }
  }
  return wf;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
  const dir = path.join(root, CHANGESET_DIR);
  const snapshot = JSON.parse(readFileSync(path.join(root, SNAPSHOT_PATH), "utf8"));
  const liveBody = snapshot.nodes.find((n) => n.name === "Generate Report").parameters.jsonBody;
  const generateReportBody = buildGenerateReportBody(liveBody);
  writeFileSync(path.join(dir, "generate-report.jsonBody.txt"), `${generateReportBody}\n`);
  const plan = buildPlan({
    runtimeConfigCode: readFileSync(path.join(dir, "runtime-config.jsCode.js"), "utf8").trimEnd(),
    missingPromptCode: readFileSync(path.join(dir, "missing-prompt.jsCode.js"), "utf8").trimEnd(),
    generateReportBody,
  });
  writeFileSync(path.join(dir, "apply-plan.json"), `${JSON.stringify(plan, null, 2)}\n`);
  writeFileSync(path.join(dir, "proposed.nem-verify.workflow.json"), `${JSON.stringify(applyPlan(snapshot, plan), null, 2)}\n`);
  process.stdout.write(`wrote generate-report.jsonBody.txt, apply-plan.json and proposed.nem-verify.workflow.json to ${CHANGESET_DIR}\n`);
}
