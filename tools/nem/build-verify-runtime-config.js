export function buildGenerateReportBody(liveBody) {
  const parts = String(liveBody).split(PROMPT_READ_BEFORE);
  if (parts.length !== 2) throw new Error(`Generate Report must read ${PROMPT_READ_BEFORE} exactly once, found ${parts.length - 1}`);
  return parts.join(PROMPT_READ_AFTER);
}

