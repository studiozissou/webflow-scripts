// Builds the Publish Prompt workflow's Serialise Code node from the tested serialiser and validator modules, and writes it into the workflow snapshot and the changeset, so the node always runs exactly the code the tests cover.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SNAPSHOT_PATH = "projects/nem-life/.claude/backend/nem-publish-prompt.workflow.json";
export const SERIALISE_PATH = "projects/nem-life/.claude/backend/changesets/nem-publish-prompt-v1/serialise.jsCode.js";
export const MODULE_PATHS = ["tools/nem/notion-to-prompt.js", "tools/nem/validate-prompt.js"];

const HEADER =
  "// Turns the Notion runtime page into the report prompt, validates it and picks the next version; generated by tools/nem/build-publish-prompt.js from tools/nem/notion-to-prompt.js and tools/nem/validate-prompt.js, so edit those and rebuild, never this node.";

export const SERIALISE_BODY = `const config = $('Config').first().json;
const fetchedBlocks = $('Fetch Notion Blocks').all().map((item) => item.json).filter((block) => block && typeof block.type === 'string');
const versionRows = $('Load Prompt Versions').all().map((item) => item.json).filter((entry) => entry && entry.key === config.key);
const activeRow = versionRows
  .filter((entry) => entry.active === true || entry.active === 'true')
  .sort((a, b) => (Number(b.version) || 0) - (Number(a.version) || 0))[0];
const nextVersion = versionRows.reduce((highest, entry) => Math.max(highest, Number(entry.version) || 0), 0) + 1;
const statusCallout = fetchedBlocks.find((block) => block.type === 'callout');

let promptText = '';
let verdict;
try {
  promptText = normalisePrompt(notionToPrompt(fetchedBlocks));
  verdict = validatePrompt(promptText, { activeChars: activeRow ? Number(activeRow.chars) : undefined });
} catch (error) {
  promptText = '';
  verdict = { ok: false, reasons: [error.message], warnings: [], chars: 0, headings: 0 };
}
const refusals = statusCallout ? verdict.reasons : [...verdict.reasons, 'no status callout on the page'];

return [{
  json: {
    ok: refusals.length === 0,
    reasons: refusals,
    warnings: verdict.warnings,
    text: promptText,
    chars: verdict.chars,
    headings: verdict.headings,
    version: nextVersion,
    previousVersion: activeRow ? Number(activeRow.version) : null,
    calloutId: statusCallout ? statusCallout.id : null,
    key: config.key,
    publishedAt: new Date().toISOString(),
    executionId: String($execution.id)
  }
}];`;

export const moduleBody = (source) => source.replace(/^export \{[^}]*\};\n?/m, "").trimEnd();

export function buildSerialiseCode(notionSource, validateSource) {
  return [HEADER, moduleBody(notionSource), moduleBody(validateSource), SERIALISE_BODY].join("\n\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
  const [notion, validate] = MODULE_PATHS.map((p) => readFileSync(path.join(root, p), "utf8"));
  const code = buildSerialiseCode(notion, validate);
  const snapshotFile = path.join(root, SNAPSHOT_PATH);
  const workflow = JSON.parse(readFileSync(snapshotFile, "utf8"));
  const node = workflow.nodes.find((n) => n.name === "Serialise");
  if (!node) throw new Error(`${SNAPSHOT_PATH} has no Serialise node`);
  node.parameters.jsCode = code;
  writeFileSync(snapshotFile, `${JSON.stringify(workflow, null, 2)}\n`);
  writeFileSync(path.join(root, SERIALISE_PATH), `${code}\n`);
  process.stdout.write(`wrote Serialise (${code.length} chars) to ${SNAPSHOT_PATH} and ${SERIALISE_PATH}\n`);
}
